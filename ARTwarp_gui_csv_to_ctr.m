function fig = ARTwarp_gui_csv_to_ctr
% This function generates a graphical user interface to enter the
% parameters for converting some .csv files to .ctr

% Initialise the freqCol and Tempres as empty arrays so their UI fields
% show as empty initially
freqCol = [];
tempres = [];

% Get folder_name from the user
folder_name = uigetdir('*.csv', 'Select the folder containing the .csv files to convert');

% Generate window to contain UI elements
h0 = figure('Units','points', ...
'Color',[0.752941176470588 0.752941176470588 0.752941176470588],...
'DockControls','off',...
'IntegerHandle','off',...
'MenuBar','none',...
'Name','Enter the Conversion Parameters',...
'NumberTitle','off',...
'PaperPosition',[18 180 576 432], ...
'PaperUnits','points', ...
'Position',[317 241 290 300], ...
'Resize','off', ...
'Tag','conversion_parameter_GUI',...
'Visible','on');

% Label for 'folder_name' editable text box
h1 = uicontrol('Parent',h0,...
'Units','points',...
'BackgroundColor',[0.752941176470588 0.752941176470588 0.752941176470588], ...
'FontSize',10, ...
'FontUnits','points',...
'HorizontalAlignment','left',...
'Position',[100 263 150 15], ...
'String','folder_name',...
'Style','text');

% Editable text box to enter 'folder_name' value
h1 = uicontrol('Parent',h0,...
'Units','points',...
'BackgroundColor',[1 1 1], ...
'FontSize',10, ...
'FontUnits','points',...
'HorizontalAlignment','right',...
'Position',[20 263 75 20], ...
'String', folder_name,...
'Style','edit',...
'Tag','folder_name');

% Label for 'freqCol' editable text box
h1 = uicontrol('Parent',h0,...
'Units','points',...
'BackgroundColor',[0.752941176470588 0.752941176470588 0.752941176470588], ...
'FontSize',10, ...
'FontUnits','points',...
'HorizontalAlignment','left',...
'Position',[100 233 150 15], ...
'String','freqCol',...
'Style','text');

% Editable text box to enter 'freqCol' value
h1 = uicontrol('Parent',h0,...
'Units','points',...
'BackgroundColor',[1 1 1], ...
'FontSize',10, ...
'FontUnits','points',...
'HorizontalAlignment','right',...
'Position',[20 233 75 20], ...
'String', num2str(freqCol,'%i'),...
'Style','edit',...
'Tag','freqCol');

% Label for 'tempres' editable text box
h1 = uicontrol('Parent',h0,...
'Units','points',...
'BackgroundColor',[0.752941176470588 0.752941176470588 0.752941176470588], ...
'FontSize',10, ...
'FontUnits','points',...
'HorizontalAlignment','left',...
'Position',[100 200 150 15], ...
'String','tempres',...
'Style','text');

% Editable text box to enter 'tempres' value
h1 = uicontrol('Parent',h0,...
'Units','points',...
'BackgroundColor',[1 1 1], ...
'FontSize',10, ...
'FontUnits','points',...
'HorizontalAlignment','right',...
'Position',[20 200 75 20], ...
'String',num2str(tempres,'%i'),...
'Style','edit',...
'Tag','tempres');

% 'OK' button to initiate conversion, passing folder_name already collected
h1 = uicontrol('Parent',h0, ...
'Units','points', ...
'BackgroundColor',[0.752941176470588 0.752941176470588 0.752941176470588], ...
'Callback','TempRes3(false, [], [], "")', ...
'FontSize',10, ...
'FontUnits','points',...
'FontWeight','bold', ...
'ListboxTop',0, ...
'Position',[20 20 60 20], ...
'String','OK', ...
'Tag','runbutton');

% Button to cancel and close window
h1 = uicontrol('Parent',h0, ...
'Units','points', ...
'BackgroundColor',[0.752941176470588 0.752941176470588 0.752941176470588], ...
'Callback','close(gcf)', ...
'FontSize',10, ...
'FontUnits','points',...
'ListboxTop',0, ...
'Position',[190 20 60 20], ...
'String','Cancel', ...
'Tag','cancelbutton');

if nargout > 0, fig = h0; end %if the number of arguments out is > 0 (there are values in the text fields), run the figure's callback (TempRes3)